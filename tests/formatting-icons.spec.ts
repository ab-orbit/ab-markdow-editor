import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

test('heading previews have distinct hierarchy and gallery inserts icons into source and visual editing', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('heading', { name: 'Configurações', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Voltar ao editor', exact: true }).click();
  await page.getByLabel('Arquivo Markdown', { exact: true }).setInputFiles({ name: 'formatting.md', mimeType: 'text/markdown', buffer: Buffer.from('Example paragraph\n') });
  await page.getByRole('button', { name: 'Fonte', exact: true }).click();
  if (!await page.getByRole('button', { name: 'Estilo do parágrafo' }).isVisible()) await page.getByRole('button', { name: 'Mostrar formatação', exact: true }).click();
  await page.getByRole('button', { name: 'Estilo do parágrafo' }).click();
  const menu = page.getByRole('menu', { name: 'Estilo do parágrafo' });
  const sizes = await menu.locator('[data-heading-level] > span:nth-child(2) > span').evaluateAll(elements => elements.map(element => parseFloat(getComputedStyle(element).fontSize)));
  expect(sizes[1]).toBeGreaterThan(sizes[2]); expect(sizes[2]).toBeGreaterThan(sizes[3]); expect(sizes[3]).toBeGreaterThan(sizes[0]);
  await mkdir('docs/evidence/formatting-icons', { recursive: true });
  await page.setViewportSize({ width: 1440, height: 900 });
  await expect(menu.getByRole('menuitem', { name: /Título 3/ })).toBeInViewport();
  await page.screenshot({ path: 'docs/evidence/formatting-icons/heading-hierarchy-desktop.png' });
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter');
  await expect(page.locator('.cm-content')).toContainText('# Example paragraph');
  await page.locator('.cm-content').click(); await page.keyboard.press('ControlOrMeta+End');
  await page.getByRole('button', { name: 'Galeria de ícones', exact: true }).click();
  const gallery = page.getByRole('dialog', { name: 'Galeria de ícones' });
  await gallery.getByRole('searchbox', { name: 'Buscar ícones' }).fill('users');
  await expect(gallery.getByRole('button', { name: 'Inserir ícone users', exact: true })).toBeVisible();
  await page.screenshot({ path: 'docs/evidence/formatting-icons/lucide-gallery-desktop.png' });
  await gallery.getByRole('button', { name: 'Inserir ícone users', exact: true }).click();
  await expect(page.locator('.cm-content')).toContainText('data-lucide="users"');
  await page.getByRole('button', { name: 'Ler', exact: true }).click();
  await expect(page.locator('article [data-document-icon="users"] svg')).toBeVisible();
  await page.getByRole('button', { name: 'Escrever', exact: true }).click();
  const visual = page.locator('.tiptap');
  await visual.click(); await page.keyboard.press('ControlOrMeta+End');
  await page.getByRole('button', { name: 'Galeria de ícones', exact: true }).click();
  await gallery.getByRole('searchbox', { name: 'Buscar ícones' }).fill('git-branch');
  await gallery.getByRole('button', { name: 'Inserir ícone git-branch', exact: true }).click();
  await expect(visual.locator('[data-document-icon="git-branch"] svg')).toBeVisible();
  await page.getByRole('button', { name: 'Concluir edição', exact: true }).click();
  await expect(page.locator('article [data-document-icon="git-branch"] svg')).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  const closeNotes = page.getByRole('button', { name: 'Fechar lista de notas', exact: true });
  if (await closeNotes.isVisible()) await closeNotes.click();
  await page.getByRole('button', { name: 'Editar nota', exact: true }).click();
  if (!await page.getByRole('button', { name: 'Galeria de ícones', exact: true }).isVisible()) await page.getByRole('button', { name: 'Mostrar formatação', exact: true }).click();
  await page.getByRole('button', { name: 'Galeria de ícones', exact: true }).click();
  await gallery.getByRole('searchbox', { name: 'Buscar ícones' }).fill('messages');
  await expect(gallery.getByRole('button', { name: 'Inserir ícone messages-square', exact: true }).locator('svg')).toBeVisible();
  await page.screenshot({ path: 'docs/evidence/formatting-icons/lucide-gallery-mobile.png' });
});
