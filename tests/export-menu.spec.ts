import { test, expect } from '@playwright/test';
import { zipSync, unzipSync, strToU8, strFromU8 } from 'fflate';
import { readFile, mkdir } from 'node:fs/promises';

test('unified export downloads Markdown alone or ZIP with original assets', async ({page}) => {
  await page.setViewportSize({width:1440,height:900});
  await page.goto('/'); await page.getByRole('button',{name:'Voltar ao editor',exact:true}).click();
  const input=page.getByLabel('Arquivo Markdown',{exact:true});
  await input.setInputFiles({name:'plain.md',mimeType:'text/markdown',buffer:Buffer.from('# Plain\n')});
  const outline=page.getByRole('button',{name:'Mostrar outline',exact:true});
  expect(await outline.evaluate(element=>element.nextElementSibling?.getAttribute('aria-label'))).toBe('Usar tema claro');
  const menu=page.getByLabel('Exportar nota',{exact:true});
  await menu.click();
  await expect(page.getByRole('group',{name:'Formatos de exportação'}).getByRole('button')).toHaveCount(2);
  await expect(page.getByRole('button',{name:'PDF (.pdf)',exact:true})).toBeVisible();
  let pending=page.waitForEvent('download');
  await page.getByRole('button',{name:'Markdown (.md)',exact:true}).click();
  const plain=await pending;
  expect(plain.suggestedFilename()).toBe('plain.md');
  expect(await readFile((await plain.path())!,'utf8')).toBe('# Plain\n');
  const image=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aD1sAAAAASUVORK5CYII=','base64');
  const source='# With image\n\n![Pixel](assets/pixel.png)\n';
  await input.setInputFiles({name:'illustrated.zip',mimeType:'application/zip',buffer:Buffer.from(zipSync({'text.md':strToU8(source),'assets/pixel.png':image}))});
  await menu.click();
  await expect(page.getByText('ZIP com imagens anexadas',{exact:true})).toBeVisible();
  await mkdir('docs/evidence/export-menu',{recursive:true});
  await page.screenshot({path:'docs/evidence/export-menu/unified-export-desktop.png'});
  pending=page.waitForEvent('download');
  await page.getByRole('button',{name:/^Markdown \(.md\)/}).click();
  const bundle=await pending;
  expect(bundle.suggestedFilename()).toMatch(/\.zip$/);
  const files=unzipSync(new Uint8Array(await readFile((await bundle.path())!)));
  expect(strFromU8(files['text.md'])).toBe(source);
  expect(Buffer.from(files['assets/pixel.png'])).toEqual(image);
  await page.setViewportSize({width:390,height:844});
  const closeNotes=page.getByRole('button',{name:'Fechar lista de notas',exact:true});
  if(await closeNotes.isVisible()) await closeNotes.click();
  await page.getByRole('button',{name:'Mais opções da nota',exact:true}).click();
  await page.getByRole('menuitem',{name:'Exportar',exact:true}).click();
  await expect(page.getByRole('button',{name:'PDF (.pdf)',exact:true})).toBeInViewport();
  const bounds=await page.getByRole('group',{name:'Formatos de exportação'}).boundingBox();
  expect(bounds!.x).toBeGreaterThanOrEqual(0); expect(bounds!.x+bounds!.width).toBeLessThanOrEqual(390);
  await page.screenshot({path:'docs/evidence/export-menu/unified-export-mobile.png'});
});
